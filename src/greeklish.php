<?php
/**
 * Ελληνικά → Λατινικά (transliteration κατά ΕΛΟΤ 743 / ISO 843).
 *
 * Κανόνες που καλύπτει ο βασικός πίνακας:
 *   α→a, β→v, γ→g, δ→d, ε→e, ζ→z, η→i, θ→th, ι→i, κ→k, λ→l, μ→m, ν→n,
 *   ξ→x, ο→o, π→p, ρ→r, σ/ς→s, τ→t, υ→y, φ→f, χ→ch, ψ→ps, ω→o
 *
 * Επιπρόσθετα διγράμματα & context rules:
 *   αυ→av/af, ευ→ev/ef, ηυ→iv/if (πριν από ήχο φωνήεν/ηχηρό → v, αλλιώς → f)
 *   ου→ou
 *   γγ→ng, γκ→gk/g (αρχή λέξης → g, αλλιώς ng), γξ→nx, γχ→nch
 *   μπ→mp/b, ντ→nt/d (σε αρχή λέξης με "soft" μετατροπή: μπ→b, ντ→d)
 *
 * Για ονόματα αθλητών (τα οποία είναι συνήθως ΟΛΑ ΚΕΦΑΛΑΙΑ) προτιμούμε την
 * **απλή ΕΛΟΤ 743 μεταγραφή** χωρίς context rules, γιατί το context χρειάζεται
 * ολόκληρη τη λέξη σε πεζά — και για passports/official docs η απλή μορφή
 * είναι προτιμότερη.
 */

/**
 * Transliterate ελληνική ακολουθία χαρακτήρων σε λατινικούς χαρακτήρες (ΕΛΟΤ 743).
 * Διατηρεί case (ΑΛ→AL, Αλ→Al, αλ→al).
 */
function greeklish(?string $input): string
{
    if ($input === null || $input === '') {
        return '';
    }

    $s = $input;

    // Αφαίρεση τόνων/διαλυτικών — manual map γιατί intl/Normalizer μπορεί να
    // λείπει στο hosting. Καλύπτει όλους τους τονισμένους ελληνικούς χαρακτήρες
    // (μονοτονικό + πολυτονικό που τυχαίνει σε ονόματα).
    $accentMap = [
        'Ά' => 'Α', 'ά' => 'α',
        'Έ' => 'Ε', 'έ' => 'ε',
        'Ή' => 'Η', 'ή' => 'η',
        'Ί' => 'Ι', 'ί' => 'ι',
        'Ό' => 'Ο', 'ό' => 'ο',
        'Ύ' => 'Υ', 'ύ' => 'υ',
        'Ώ' => 'Ω', 'ώ' => 'ω',
        'Ϊ' => 'Ι', 'ϊ' => 'ι',
        'Ϋ' => 'Υ', 'ϋ' => 'υ',
        'ΐ' => 'ι', 'ΰ' => 'υ',
    ];
    $s = strtr($s, $accentMap);

    // Επίσης αφαίρεση τυχόν combining marks (πολυτονικά/decomposed forms)
    $stripped = preg_replace('/\p{M}+/u', '', $s);
    if (is_string($stripped)) { $s = $stripped; }

    // Διγράμματα πρώτα (πριν από τα μονά γράμματα)
    $digraphs = [
        'ΟΥ' => 'OU', 'Ου' => 'Ou', 'ου' => 'ou',
        'ΑΥ' => 'AV', 'Αυ' => 'Av', 'αυ' => 'av',
        'ΕΥ' => 'EV', 'Ευ' => 'Ev', 'ευ' => 'ev',
        'ΗΥ' => 'IV', 'Ηυ' => 'Iv', 'ηυ' => 'iv',
        'ΜΠ' => 'B',  'Μπ' => 'B',  'μπ' => 'mp',
        'ΝΤ' => 'NT', 'Ντ' => 'Nt', 'ντ' => 'nt',
        'ΓΚ' => 'GK', 'Γκ' => 'Gk', 'γκ' => 'gk',
        'ΓΓ' => 'NG', 'Γγ' => 'Ng', 'γγ' => 'ng',
        'ΓΞ' => 'NX', 'Γξ' => 'Nx', 'γξ' => 'nx',
        'ΓΧ' => 'NCH','Γχ' => 'Nch','γχ' => 'nch',
        'ΤΣ' => 'TS', 'Τσ' => 'Ts', 'τσ' => 'ts',
        'ΤΖ' => 'TZ', 'Τζ' => 'Tz', 'τζ' => 'tz',
    ];
    $s = strtr($s, $digraphs);

    // Μονά γράμματα
    $singles = [
        'Α' => 'A', 'Β' => 'V', 'Γ' => 'G', 'Δ' => 'D', 'Ε' => 'E',
        'Ζ' => 'Z', 'Η' => 'I', 'Θ' => 'TH', 'Ι' => 'I', 'Κ' => 'K',
        'Λ' => 'L', 'Μ' => 'M', 'Ν' => 'N', 'Ξ' => 'X', 'Ο' => 'O',
        'Π' => 'P', 'Ρ' => 'R', 'Σ' => 'S', 'Τ' => 'T', 'Υ' => 'Y',
        'Φ' => 'F', 'Χ' => 'CH', 'Ψ' => 'PS', 'Ω' => 'O',
        'α' => 'a', 'β' => 'v', 'γ' => 'g', 'δ' => 'd', 'ε' => 'e',
        'ζ' => 'z', 'η' => 'i', 'θ' => 'th', 'ι' => 'i', 'κ' => 'k',
        'λ' => 'l', 'μ' => 'm', 'ν' => 'n', 'ξ' => 'x', 'ο' => 'o',
        'π' => 'p', 'ρ' => 'r', 'σ' => 's', 'ς' => 's', 'τ' => 't',
        'υ' => 'y', 'φ' => 'f', 'χ' => 'ch', 'ψ' => 'ps', 'ω' => 'o',
    ];
    $s = strtr($s, $singles);

    // Title-case fix: όταν ΚΕΦΑΛΑΙΟ γράμμα-που-γίνεται-διγράμμα (Χ→CH, Θ→TH,
    // Ψ→PS, Γγ→NG, Γχ→NCH, Γξ→NX) ακολουθείται από πεζό, το κάνουμε title case
    // (π.χ. Χρήστος → Christos αντί CHristos). Όταν ακολουθεί άλλο κεφαλαίο
    // (π.χ. ΧΡΗΣΤΟΣ), μένει όλα κεφαλαία (CHRISTOS).
    foreach ([
        'NCH' => 'Nch',
        'CH'  => 'Ch',
        'TH'  => 'Th',
        'PS'  => 'Ps',
        'NG'  => 'Ng',
        'NX'  => 'Nx',
    ] as $big => $small) {
        $s = preg_replace('/' . $big . '(?=[a-z])/u', $small, $s) ?? $s;
    }

    return $s;
}
